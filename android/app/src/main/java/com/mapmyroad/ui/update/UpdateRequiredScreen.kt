/**
 * Full-screen "Update required" gate (UI_UX_GUIDELINES.md section 8), shown by the root gate after the server
 * answered `426 APP_UPDATE_REQUIRED` (API_SPEC.md section 6). Never shown while a trip is active.
 */
@Composable
fun UpdateRequiredScreen(
    onUpdate: () -> Unit,
    modifier: Modifier = Modifier,
) {
    Surface(modifier = modifier.fillMaxSize()) {
        Column(
            modifier =
                Modifier
                    .fillMaxSize()
                    .safeDrawingPadding()
                    .verticalScroll(rememberScrollState())
                    .padding(24.dp),
            verticalArrangement = Arrangement.spacedBy(16.dp, Alignment.CenterVertically),
            horizontalAlignment = Alignment.CenterHorizontally,
        ) {
            Icon(
                imageVector = Icons.Filled.Info,
                contentDescription = null,
                tint = MaterialTheme.colorScheme.primary,
                modifier = Modifier.size(48.dp),
            )
            Text(
                text = stringResource(R.string.update_title),
                style = MaterialTheme.typography.headlineSmall,
                textAlign = TextAlign.Center,
                modifier = Modifier.semantics { heading() },
            )
            Text(
                text = stringResource(R.string.update_body),
                style = MaterialTheme.typography.bodyLarge,
                textAlign = TextAlign.Center,
            )
            Button(
                onClick = onUpdate,
                modifier = Modifier.fillMaxWidth().heightIn(min = 56.dp),
            ) {
                Text(text = stringResource(R.string.update_button))
            }
        }
    }
}

